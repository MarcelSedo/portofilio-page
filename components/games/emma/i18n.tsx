/** First visit: Slovak or Czech browsers start in Slovak, everyone else in English. */
export function defaultLang(): Lang {
  if (typeof navigator === "undefined") return "en";
  return /^(sk|cs)\b/i.test(navigator.language) ? "sk" : "en";
}
